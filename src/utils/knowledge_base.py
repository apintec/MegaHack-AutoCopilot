# ==================== 像素当量与精度计算 ====================

def calculate_resolution(FOV_mm, precision_mm, safety_factor=2.0):
    """
    计算所需相机分辨率
    
    参数:
        FOV_mm: 视野范围 (mm)
        precision_mm: 检测精度要求 (mm)
        safety_factor: 安全系数 (默认2.0)
    
    返回:
        所需像素数
    """
    pixels = (FOV_mm / precision_mm) * safety_factor
    return int(pixels)

def calculate_pixel_size(sensor_resolution, FOV_mm):
    """
    计算像素尺寸
    
    参数:
        sensor_resolution: 传感器像素数
        FOV_mm: 视野范围 (mm)
    
    返回:
        像素尺寸 (mm/pixel)
    """
    return FOV_mm / sensor_resolution

def calculate_physical_size(pixels, pixel_size_mm):
    """
    计算物理尺寸
    
    参数:
        pixels: 像素数
        pixel_size_mm: 像素尺寸 (mm/pixel)
    
    返回:
        物理尺寸 (mm)
    """
    return pixels * pixel_size_mm

